#!/usr/bin/env node
/**
 * Cache-busting stamp for the static (no build step) GitHub Pages deploy.
 *
 * Why: Pages serves JS with a multi-hour max-age and the app is a graph of
 * native ES modules with plain relative imports. After a deploy, a warm
 * browser could combine a NEW importer with an OLD cached dependency; one
 * missing named export (e.g. `mergeRemoteRoom`) makes the whole module graph
 * fail to link, so no click handler is ever bound and every tab/link looks
 * dead. Reproduced 2026-10-29 by serving b488699's lobby.js beside 7b9709e's
 * systems.js: "SyntaxError: The requested module '../game/lobby.js' does not
 * provide an export named 'mergeRemoteRoom'", and the Shop/Cards tabs no
 * longer responded.
 *
 * What it does: writes an import map into index.html that maps every module
 * under src/ to `<path>?v=<content hash>`, and stamps the entry script and
 * the two stylesheets the same way. A changed file gets a new URL; an
 * unchanged file keeps its URL (and its cache). tests/assets.test.js fails if
 * index.html is stale, so `npm test` catches a forgotten restamp.
 *
 * Usage: node tools/stamp-assets.mjs        (rewrite index.html)
 *        node tools/stamp-assets.mjs --check (exit 1 if stale)
 */
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export function hashOf(path) {
  return createHash("sha256").update(readFileSync(path)).digest("hex").slice(0, 10);
}

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (name.endsWith(".js")) out.push(full);
  }
  return out;
}

export function moduleFiles() {
  return walk(join(root, "src")).map((full) => `./${relative(root, full).split(sep).join("/")}`);
}

export const STYLESHEETS = ["./styles.css", "./battlefield.css"];
export const ENTRY = "./src/main.js";

export function expectedStamp() {
  const imports = {};
  for (const rel of moduleFiles()) imports[rel] = `${rel}?v=${hashOf(join(root, rel))}`;
  const css = Object.fromEntries(STYLESHEETS.map((rel) => [rel, `${rel}?v=${hashOf(join(root, rel))}`]));
  const build = createHash("sha256")
    .update(JSON.stringify({ imports, css }))
    .digest("hex")
    .slice(0, 10);
  return { imports, css, build, entry: imports[ENTRY] };
}

const START = "<!-- asset-stamp:start (generated by tools/stamp-assets.mjs; do not edit by hand) -->";
const END = "<!-- asset-stamp:end -->";

export function renderStamp(stamp) {
  const map = JSON.stringify({ imports: stamp.imports }, null, 2)
    .split("\n")
    .map((line) => `  ${line}`)
    .join("\n");
  return [
    START,
    `<meta name="veylattice-build" content="${stamp.build}">`,
    `<script type="importmap">`,
    map,
    `</script>`,
    ...STYLESHEETS.map((rel) => `<link rel="stylesheet" href="${stamp.css[rel]}">`),
    END,
  ].join("\n");
}

export function applyStamp(html, stamp) {
  let out = html;
  const block = renderStamp(stamp);
  if (out.includes(START)) {
    out = out.replace(new RegExp(`${escape(START)}[\\s\\S]*?${escape(END)}`), block);
  } else {
    // First run: drop the plain stylesheet links and insert the block in <head>.
    for (const rel of STYLESHEETS) out = out.replace(new RegExp(`<link rel="stylesheet" href="${escape(rel)}(\\?v=[0-9a-f]+)?">\\n?`), "");
    out = out.replace("</head>", `${block}\n</head>`);
  }
  out = out.replace(
    /<script type="module" src="\.\/src\/main\.js(\?v=[0-9a-f]+)?"><\/script>/,
    `<script type="module" src="${stamp.entry}"></script>`,
  );
  return out;
}

function escape(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const indexPath = join(root, "index.html");
  const html = readFileSync(indexPath, "utf8");
  const next = applyStamp(html, expectedStamp());
  if (process.argv.includes("--check")) {
    if (next !== html) {
      console.error("index.html asset stamp is stale: run `npm run stamp`.");
      process.exit(1);
    }
    console.log("index.html asset stamp is current.");
  } else if (next !== html) {
    writeFileSync(indexPath, next);
    console.log(`index.html stamped (build ${expectedStamp().build}).`);
  } else {
    console.log("index.html already current.");
  }
}
